using Content.Client.UserInterface.Controls;
using Content.Shared.CMU14.Survivors.Setup;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Survivors;

[GenerateTypedNameReferences]
public sealed partial class SurvivorSetupWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private const int RandomCharacterId = -1;
    private TimeSpan _phaseEnd;

    public event Action<string>? OnVote;
    public event Action<int>? OnClaim;
    public event Action<int?>? OnCharacter;

    public SurvivorSetupWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CharacterSelect.OnItemSelected += args =>
        {
            CharacterSelect.SelectId(args.Id);
            OnCharacter?.Invoke(args.Id == RandomCharacterId ? null : args.Id);
        };
    }

    public void UpdateState(SurvivorSetupEuiState state)
    {
        _phaseEnd = state.PhaseEnd;
        var voting = state.Phase == SurvivorSetupPhase.Vote;
        PhaseLabel.Text = Loc.GetString(voting ? "cmu-survivor-setup-vote" : "cmu-survivor-setup-pick");
        VotePanel.Visible = voting;
        PickPanel.Visible = !voting;

        VotePanel.RemoveAllChildren();
        foreach (var party in state.Parties)
        {
            var text = Loc.GetString("cmu-survivor-setup-party", ("name", party.Name), ("votes", party.Votes));
            var button = new Button
            {
                Text = party.Id == state.MyVote ? Loc.GetString("cmu-survivor-setup-mine", ("text", text)) : text,
                HorizontalExpand = true,
            };
            var id = party.Id;
            button.OnPressed += _ => OnVote?.Invoke(id);
            VotePanel.AddChild(button);
        }

        Slots.RemoveAllChildren();
        foreach (var slot in state.Slots)
        {
            var text = slot.ClaimedBy == null
                ? Loc.GetString("cmu-survivor-setup-slot-free", ("role", slot.Name))
                : Loc.GetString("cmu-survivor-setup-slot-taken", ("role", slot.Name), ("player", slot.ClaimedBy));
            var mine = slot.Index == state.MySlot;
            var button = new Button
            {
                Text = mine ? Loc.GetString("cmu-survivor-setup-mine", ("text", text)) : text,
                Disabled = slot.ClaimedBy != null && !mine,
                HorizontalExpand = true,
            };
            var index = slot.Index;
            button.OnPressed += _ => OnClaim?.Invoke(index);
            Slots.AddChild(button);
        }

        CharacterSelect.Clear();
        CharacterSelect.AddItem(Loc.GetString("cmu-survivor-setup-random"), RandomCharacterId);
        foreach (var character in state.Characters)
        {
            CharacterSelect.AddItem(character.Name, character.Slot);
        }

        CharacterSelect.SelectId(state.MyCharacter ?? RandomCharacterId);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var left = Math.Max(0, (int) Math.Ceiling((_phaseEnd - _timing.CurTime).TotalSeconds));
        TimerLabel.Text = Loc.GetString("cmu-survivor-setup-time", ("seconds", left));
    }
}