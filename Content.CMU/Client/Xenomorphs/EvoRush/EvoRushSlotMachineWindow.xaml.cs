using Content.Client.UserInterface.Controls;
using Content.Shared.CMU14.Xenonids.EvoRush;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.CMU14.Xenomorphs.EvoRush;

[GenerateTypedNameReferences]
public sealed partial class EvoRushSlotMachineWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IGameTiming _timing = default!;

    private const float ReelStep = 0.08f;

    private EvoRushSlotMachineBuiState? _state;
    private float _accumulator;
    private int _reelIndex;
    private bool _revealed;

    public event Action<bool>? OnDecision;

    public EvoRushSlotMachineWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        AcceptButton.OnPressed += _ => OnDecision?.Invoke(true);
        DeclineButton.OnPressed += _ => OnDecision?.Invoke(false);
    }

    public void SetState(EvoRushSlotMachineBuiState state)
    {
        _state = state;
        _revealed = false;
        _reelIndex = 0;
        AcceptButton.Disabled = true;
        DeclineButton.Disabled = true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_state == null)
            return;

        var now = _timing.CurTime;
        if (now < _state.SpinEnd && _state.Reel.Count > 0)
        {
            _accumulator += args.DeltaSeconds;
            if (_accumulator >= ReelStep)
            {
                _accumulator = 0;
                _reelIndex = (_reelIndex + 1) % _state.Reel.Count;
                Reel.Text = CasteName(_state.Reel[_reelIndex]);
            }

            Status.Text = Loc.GetString("cmu-evo-rush-slot-spinning");
            return;
        }

        if (!_revealed)
        {
            _revealed = true;
            Reel.Text = CasteName(_state.Result);
            AcceptButton.Disabled = false;
            DeclineButton.Disabled = false;
        }

        var left = Math.Max(0, (int) Math.Ceiling((_state.DecideEnd - now).TotalSeconds));
        Status.Text = Loc.GetString("cmu-evo-rush-slot-decide", ("seconds", left));
    }

    private string CasteName(EntProtoId id)
        => _prototypes.TryIndex(id, out var proto) ? proto.Name : id.Id;
}