using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared.CMU14.Xenonids.EvoRush;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.CMU14.Xenonids.EvoRush;

[GenerateTypedNameReferences]
public sealed partial class EvoRushCastePriorityWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly List<EntProtoId> _order = new();
    private readonly Dictionary<EntProtoId, Button> _buttons = new();
    private int _required;

    public event Action<List<EntProtoId>>? OnSubmit;

    public EvoRushCastePriorityWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SubmitButton.OnPressed += _ => OnSubmit?.Invoke(_order.ToList());
    }

    public void Update(EvoRushCastePriorityBuiState state)
    {
        Castes.RemoveAllChildren();
        _buttons.Clear();
        _order.Clear();
        _order.AddRange(state.Current);
        _required = Math.Min(3, state.Castes.Count);

        foreach (var caste in state.Castes)
        {
            var button = new Button { HorizontalExpand = true };
            button.OnPressed += _ => Toggle(caste);
            _buttons[caste] = button;
            Castes.AddChild(button);
        }

        Refresh();
    }

    private void Toggle(EntProtoId caste)
    {
        if (!_order.Remove(caste) && _order.Count < _required)
            _order.Add(caste);

        Refresh();
    }

    private void Refresh()
    {
        foreach (var (caste, button) in _buttons)
        {
            var name = _prototypes.TryIndex(caste, out var proto) ? proto.Name : caste.Id;
            var rank = _order.IndexOf(caste);
            button.Text = rank < 0
                ? name
                : Loc.GetString("cmu-evo-rush-priority-entry", ("rank", rank + 1), ("caste", name));
        }

        SubmitButton.Disabled = _order.Count < _required;
    }
}